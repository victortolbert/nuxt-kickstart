/**
 * Build Iconify class string for a given icon set, semantic name, and variant
 */
export function buildIconClass(
  setId: IconSetId,
  iconName: string,
  variant?: IconVariant,
): string {
  const iconSet = iconSets.find(set => set.id === setId)
  if (!iconSet) {
    throw new Error(`Unknown icon set: ${setId}`)
  }

  const iconMapping = iconMappings[iconName]
  if (!iconMapping) {
    throw new Error(`Unknown icon name: ${iconName}`)
  }

  const iconIdentifier = iconMapping[setId]
  const selectedVariant = variant || iconSet.defaultVariant

  // Handle Remix icon naming convention (line/fill suffixes).
  // Suffix-less identifiers (e.g. `draggable`, `hashtag`) have a single
  // style in the collection and must be used as-is.
  if (setId === 'remix') {
    if (iconIdentifier.endsWith('-line') || iconIdentifier.endsWith('-fill')) {
      const suffix = selectedVariant === 'filled' ? 'fill' : 'line'
      const base = iconIdentifier.replace(REMIX_SUFFIX_REGEX, '')
      return `i-${iconSet.prefix}-${base}-${suffix}`
    }
    return `i-${iconSet.prefix}-${iconIdentifier}`
  }

  // Handle Phosphor icon naming convention (regular/fill/duotone suffixes)
  if (setId === 'phosphor') {
    const suffix = selectedVariant === 'filled' ? 'fill' : selectedVariant === 'duotone' ? 'duotone' : ''
    return suffix ? `i-${iconSet.prefix}-${iconIdentifier}-${suffix}` : `i-${iconSet.prefix}-${iconIdentifier}`
  }

  // Handle Heroicons: outline names are plain, solid uses a `-solid` suffix
  if (setId === 'heroicons') {
    return selectedVariant === 'solid'
      ? `i-${iconSet.prefix}-${iconIdentifier}-solid`
      : `i-${iconSet.prefix}-${iconIdentifier}`
  }

  // Handle Tabler (outline/filled variants). Most Tabler icons have no
  // filled counterpart — fall back to outline rather than a missing icon.
  if (setId === 'tabler') {
    if (selectedVariant === 'filled' && TABLER_FILLED.has(iconIdentifier))
      return `i-${iconSet.prefix}-${iconIdentifier}-filled`
    return `i-${iconSet.prefix}-${iconIdentifier}`
  }

  // Lucide only has outline variant
  return `i-${iconSet.prefix}-${iconIdentifier}`
}
