import type { GeneratedFile } from './shared'
import { collectVarTokens, formatTokenValue, unwrapHelium } from './shared'

/**
 * CSS custom properties (`:root { --name: value; }`).
 */
export function generateCSSVariables(tokens: Record<string, any>, options: Record<string, any>): GeneratedFile {
  const selector = options.selector || ':root'
  const prefix = options.prefix ? `${options.prefix}-` : ''

  const lines: string[] = [`${selector} {`]
  collectVarTokens(unwrapHelium(tokens), (varName, value) => {
    lines.push(`  --${prefix}${varName}: ${value};`)
  })
  lines.push('}')

  return { ext: 'css', content: lines.join('\n') }
}

/**
 * Component-scoped CSS custom properties (`.cmp-x.theme { --x-name: value; }`).
 */
export function generateCSSComponents(tokens: Record<string, any>, _options: Record<string, any>): GeneratedFile {
  const lines: string[] = []
  const innerTokens = unwrapHelium(tokens)
  const components = innerTokens.components || {}

  for (const [componentName, componentObj] of Object.entries(components)) {
    if (!componentObj || typeof componentObj !== 'object')
      continue

    const selectorBase = `cmp-${componentName}`

    for (const [themeName, themeObj] of Object.entries(componentObj as Record<string, any>)) {
      if (!themeObj || typeof themeObj !== 'object')
        continue

      const themeSelector = `.${selectorBase}.${themeName.replaceAll(' ', '-').toLowerCase()}`
      const vars: string[] = []

      for (const [tokenName, tokenValue] of Object.entries(themeObj as Record<string, any>)) {
        if (tokenValue && typeof tokenValue === 'object' && '$value' in tokenValue) {
          const varName = tokenName.replaceAll(' ', '-').toLowerCase()
          vars.push(`  --${componentName}-${varName}: ${tokenValue.$value};`)
        }
      }

      if (vars.length > 0) {
        lines.push(`${themeSelector} {`)
        lines.push(...vars)
        lines.push('}')
        lines.push('')
      }
    }
  }

  return { ext: 'css', content: lines.join('\n') }
}

/**
 * Helium/Nova-style CSS — typography classes + component theme selectors.
 * Matches the Style Dictionary configuration used in the Nova project.
 */
export function generateHeliumCSS(tokens: Record<string, any>, _options: Record<string, any>): GeneratedFile {
  const lines: string[] = []

  const now = new Date()
  const formattedDateTime = now.toLocaleString('en-US', {
    month: '2-digit',
    day: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
  }).replace(',', '')

  lines.push('/***********************************************')
  lines.push(`* THIS FILE IS AUTO GENERATED ON ${formattedDateTime}`)
  lines.push('* DO NOT EDIT THIS FILE')
  lines.push('***********************************************/')
  lines.push('')

  const innerTokens = unwrapHelium(tokens)

  // Typography (rte)
  const rte = innerTokens.rte || {}
  if (Object.keys(rte).length > 0) {
    lines.push('/*--- TYPOGRAPHY ---*/')

    for (const [typographyName, typographyToken] of Object.entries(rte)) {
      if (!typographyToken || typeof typographyToken !== 'object')
        continue

      const typographyValue = (typographyToken as Record<string, any>).$value
        || (typographyToken as Record<string, any>).original?.$value
        || typographyToken

      if (!typographyValue || typeof typographyValue !== 'object')
        continue

      const className = `.${typographyName.replaceAll(' ', '-').replaceAll('/', '-').toLowerCase()}`

      const fontFamily = typographyValue.fontFamily ? `'${typographyValue.fontFamily}'` : 'inherit'
      const fontSize = typographyValue.fontSize || 'inherit'
      const fontWeight = typographyValue.fontWeight || 400
      const lineHeight = typographyValue.lineHeight || 'normal'
      const letterSpacing = typographyValue.letterSpacing?.$value || typographyValue.letterSpacing || 'normal'
      const textTransform = typographyValue.textCase?.$value || typographyValue.textCase || 'none'

      lines.push(`${className} {`)
      lines.push(`  font-family: ${fontFamily}, sans-serif;`)
      lines.push(`  font-size: ${fontSize};`)
      lines.push(`  font-weight: ${fontWeight};`)
      lines.push(`  line-height: ${lineHeight};`)
      lines.push(`  letter-spacing: ${letterSpacing};`)
      lines.push(`  text-transform: ${textTransform};`)
      lines.push('}')
      lines.push('')
    }
  }

  // Component tokens
  const components = innerTokens.components || {}
  for (const [componentName, componentObj] of Object.entries(components)) {
    if (!componentObj || typeof componentObj !== 'object')
      continue

    const selectorBase = `cmp-${componentName}`
    lines.push('')
    lines.push('')
    lines.push(`/*--- ${componentName.toUpperCase()} ---*/`)

    for (const [themeName, themeObj] of Object.entries(componentObj as Record<string, any>)) {
      if (!themeObj || typeof themeObj !== 'object')
        continue
      if (themeName === '$extensions')
        continue

      const themeSelector = `.${selectorBase}.${themeName.replaceAll(' ', '-').toLowerCase()}`
      const vars: string[] = []

      for (const [tokenName, tokenValue] of Object.entries(themeObj as Record<string, any>)) {
        if (tokenValue && typeof tokenValue === 'object' && '$value' in tokenValue) {
          const varName = tokenName.replaceAll(' ', '-').toLowerCase()
          const value = formatTokenValue(tokenValue.$value)
          vars.push(`  --${componentName}-${varName}: ${value};`)
        }
      }

      if (vars.length > 0) {
        lines.push(`${themeSelector} {`)
        lines.push(...vars)
        lines.push('}')
      }
    }
  }

  return { ext: 'css', content: lines.join('\n') }
}
