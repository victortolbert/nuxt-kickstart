/**
 * Style Dictionary integration for token transformation
 * Uses Style Dictionary v5 programmatically without file I/O
 */

import type { Config } from 'style-dictionary'
import StyleDictionary from 'style-dictionary'

// Type definitions
interface TransformResult {
  output: string
  destination?: string
}

/**
 * Register Nova/Helium custom transforms
 * These match the transforms in lib/style-dictionary/sd.config.js
 */
function registerNovaTransforms(sd: typeof StyleDictionary) {
  // Generate metadata for token categorizing tree
  sd.registerTransform({
    name: 'attribute/nova',
    type: 'attribute',
    transform: (token) => {
      const attrNames = ['datatype', 'category', 'type', 'theme', 'subitem', 'state']
      const originalAttrs = token.attributes || {}
      const generatedAttrs: Record<string, string> = {}

      for (let i = 0; i < token.path.length && i < attrNames.length; i++) {
        generatedAttrs[attrNames[i]!] = token.path[i]!
      }
      return Object.assign(generatedAttrs, originalAttrs)
    },
  })

  // Transform values with spaces to dashed, strip base path from token name
  sd.registerTransform({
    name: 'name/nova',
    type: 'name',
    transform: (token) => {
      if (token.attributes?.category === 'components') {
        const fullPath = token.path.join('-')
        const pathChange = fullPath.split(`${token.attributes.theme}-`)[1]
        return pathChange?.replaceAll(' ', '-').toLowerCase() || fullPath.replaceAll(' ', '-').toLowerCase()
      }
      return token.path.join('-').replaceAll(' ', '-').toLowerCase()
    },
  })

  // Wrap font family in quotes for typography tokens
  sd.registerTransform({
    name: 'typography/fontFamily-wrap-quotes',
    type: 'value',
    filter: token => token.$type === 'typography' || token.type === 'typography',
    transform: (token) => {
      const typography = token.$value || token.value
      if (typography && typeof typography === 'object' && 'fontFamily' in typography) {
        return {
          ...typography,
          fontFamily: `"${typography.fontFamily}"`,
        }
      }
      return typography
    },
  })
}

/**
 * Register Nova/Helium custom CSS format
 * Outputs component-scoped CSS variables with typography classes
 */
function registerNovaFormats(sd: typeof StyleDictionary) {
  sd.registerFormat({
    name: 'css/helium',
    format: ({ dictionary }) => {
      const now = new Date()
      const formattedDateTime = now.toLocaleString('en-US', {
        month: '2-digit',
        day: '2-digit',
        year: 'numeric',
        hour: '2-digit',
        minute: '2-digit',
        hour12: false,
      }).replace(',', '')

      const lines: string[] = [
        '/***********************************************',
        `* THIS FILE IS AUTO GENERATED ON ${formattedDateTime}`,
        '* DO NOT EDIT THIS FILE',
        '***********************************************/',
        '',
      ]

      // Access tokens - handle both wrapped and unwrapped structures
      const tokens = dictionary.tokens as Record<string, unknown>
      const innerTokens = (tokens.tokens && typeof tokens.tokens === 'object' ? tokens.tokens : tokens) as Record<string, unknown>

      // TYPOGRAPHY
      const rte = innerTokens.rte as Record<string, unknown> | undefined
      if (rte && Object.keys(rte).length > 0) {
        lines.push('/*--- TYPOGRAPHY ---*/')

        for (const [typographyName, typographyToken] of Object.entries(rte)) {
          if (!typographyToken || typeof typographyToken !== 'object')
            continue

          const tokenObj = typographyToken as Record<string, unknown>
          const typographyValue = (tokenObj.original as Record<string, unknown>)?.$value
            || tokenObj.$value
            || tokenObj

          if (!typographyValue || typeof typographyValue !== 'object')
            continue

          const typVal = typographyValue as Record<string, unknown>
          const className = `.${typographyName.replaceAll(' ', '-').replaceAll('/', '-').toLowerCase()}`

          const fontFamily = typVal.fontFamily ? `'${typVal.fontFamily}'` : 'inherit'
          const fontSize = typVal.fontSize || 'inherit'
          const fontWeight = typVal.fontWeight || 400
          const lineHeight = typVal.lineHeight || 'normal'
          const letterSpacing = (typVal.letterSpacing as Record<string, unknown>)?.$value || typVal.letterSpacing || 'normal'
          const textTransform = (typVal.textCase as Record<string, unknown>)?.$value || typVal.textCase || 'none'

          lines.push(`${className} {`)
          lines.push(`  font-family: ${fontFamily}, sans-serif;`)
          lines.push(`  font-size: ${fontSize};`)
          lines.push(`  font-weight: ${fontWeight};`)
          lines.push(`  line-height: ${lineHeight};`)
          lines.push(`  letter-spacing: ${letterSpacing};`)
          lines.push(`  text-transform: ${textTransform};`)
          lines.push('}')
          lines.push('')
        }
      }

      // COMPONENTS
      const components = innerTokens.components as Record<string, unknown> | undefined
      if (components) {
        for (const [componentName, componentObj] of Object.entries(components)) {
          if (!componentObj || typeof componentObj !== 'object')
            continue

          const selectorBase = `cmp-${componentName}`
          lines.push('')
          lines.push(`/*--- ${componentName.toUpperCase()} ---*/`)

          for (const [themeName, themeObj] of Object.entries(componentObj as Record<string, unknown>)) {
            if (!themeObj || typeof themeObj !== 'object')
              continue
            if (themeName === '$extensions')
              continue

            const themeSelector = `.${selectorBase}.${themeName.replaceAll(' ', '-').toLowerCase()}`
            const vars: string[] = []

            for (const [tokenName, tokenValue] of Object.entries(themeObj as Record<string, unknown>)) {
              if (tokenValue && typeof tokenValue === 'object') {
                const tv = tokenValue as Record<string, unknown>
                // Use the transformed name if available, otherwise generate it
                const varName = (tv.name as string) || tokenName.replaceAll(' ', '-').toLowerCase()
                const value = formatCSSValue(tv.$value ?? tv.value)
                vars.push(`  --${componentName}-${varName}: ${value};`)
              }
            }

            if (vars.length > 0) {
              lines.push(`${themeSelector} {`)
              lines.push(...vars)
              lines.push('}')
            }
          }
        }
      }

      return lines.join('\n')
    },
  })

  // Standard CSS variables format (flat)
  sd.registerFormat({
    name: 'css/variables-flat',
    format: ({ dictionary, options }) => {
      const selector = options?.selector || ':root'
      const prefix = options?.prefix || ''

      const lines: string[] = [`${selector} {`]

      for (const token of dictionary.allTokens) {
        const value = formatCSSValue(token.$value ?? token.value)
        lines.push(`  --${prefix}${token.name}: ${value};`)
      }

      lines.push('}')
      return lines.join('\n')
    },
  })
}

/**
 * Format a value for CSS output
 * Handles complex values like typography, borders, shadows
 */
function formatCSSValue(value: unknown): string {
  if (value === null || value === undefined) {
    return 'inherit'
  }

  if (typeof value === 'string' || typeof value === 'number') {
    return String(value)
  }

  if (typeof value !== 'object') {
    return String(value)
  }

  const obj = value as Record<string, unknown>

  // Typography: fontWeight fontSize/lineHeight "fontFamily"
  if ('fontFamily' in obj || 'fontSize' in obj) {
    const fontWeight = obj.fontWeight || 400
    const fontSize = obj.fontSize || '16px'
    const lineHeight = obj.lineHeight || 'normal'
    const fontFamily = obj.fontFamily || 'sans-serif'
    return `${fontWeight} ${fontSize}/${lineHeight} "${fontFamily}"`
  }

  // Shadow: offsetX offsetY blur spread color
  if (('offsetX' in obj || 'x' in obj || 'offsetY' in obj || 'y' in obj) && !('style' in obj)) {
    const offsetX = obj.offsetX ?? obj.x ?? '0px'
    const offsetY = obj.offsetY ?? obj.y ?? '0px'
    const blur = obj.blur ?? '0px'
    const spread = obj.spread ?? '0px'
    const color = obj.color || 'rgba(0,0,0,0.1)'
    return `${offsetX} ${offsetY} ${blur} ${spread} ${color}`
  }

  // Border: width style color
  if ('style' in obj || ('width' in obj && 'color' in obj)) {
    const width = obj.width || '1px'
    const style = obj.style || 'solid'
    const color = obj.color || 'currentColor'
    return `${width} ${style} ${color}`
  }

  return JSON.stringify(value)
}

/**
 * Transform tokens using Style Dictionary
 */
export async function transformWithStyleDictionary(
  tokens: Record<string, unknown>,
  formatId: string,
  options: Record<string, unknown> = {},
): Promise<{ content: string, filename: string }> {
  // Register custom transforms and formats
  registerNovaTransforms(StyleDictionary)
  registerNovaFormats(StyleDictionary)

  // Map format IDs to SD configurations
  const formatConfigs: Record<string, { format: string, transforms: string[], ext: string }> = {
    'css': {
      format: 'css/variables',
      transforms: ['name/kebab'],
      ext: 'css',
    },
    'css-components': {
      format: 'css/variables-flat',
      transforms: ['attribute/nova', 'name/nova'],
      ext: 'css',
    },
    'helium-css': {
      format: 'css/helium',
      transforms: [
        'attribute/nova',
        'name/nova',
        'typography/fontFamily-wrap-quotes',
        'typography/css/shorthand',
        'border/css/shorthand',
        'shadow/css/shorthand',
      ],
      ext: 'css',
    },
    'scss-vars': {
      format: 'scss/variables',
      transforms: ['name/kebab'],
      ext: 'scss',
    },
    'json-flat': {
      format: 'json/flat',
      transforms: [],
      ext: 'json',
    },
    'json-nested': {
      format: 'json/nested',
      transforms: [],
      ext: 'json',
    },
    'js-esm': {
      format: 'javascript/es6',
      transforms: ['name/camel'],
      ext: 'js',
    },
    'ts': {
      format: 'typescript/es6-declarations',
      transforms: ['name/camel'],
      ext: 'd.ts',
    },
  }

  const formatConfig = formatConfigs[formatId]
  if (!formatConfig) {
    throw new Error(`Unsupported format: ${formatId}`)
  }

  // Build SD configuration
  const selector = (options.selector as string) || ':root'
  const prefix = (options.prefix as string) || ''
  const outputReferences = (options.outputReferences as boolean) ?? true

  const config = {
    tokens,
    platforms: {
      target: {
        transforms: formatConfig.transforms,
        files: [{
          destination: `tokens.${formatConfig.ext}`,
          format: formatConfig.format,
          options: {
            selector,
            prefix,
            outputReferences,
          },
        }],
      },
    },
  } as unknown as Config

  // Create SD instance and format
  const sd = new StyleDictionary(config)
  const results = await sd.formatPlatform('target') as TransformResult[]

  if (!results || results.length === 0) {
    throw new Error('Style Dictionary returned no output')
  }

  return {
    content: results[0]!.output as string,
    filename: `tokens.${formatConfig.ext}`,
  }
}

/**
 * Check if Style Dictionary supports a format
 */
export function isStyleDictionaryFormat(formatId: string): boolean {
  const supportedFormats = [
    'css',
    'css-components',
    'helium-css',
    'scss-vars',
    'json-flat',
    'json-nested',
    'js-esm',
    'ts',
  ]
  return supportedFormats.includes(formatId)
}
